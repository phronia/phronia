#!/usr/bin/env node
/**
 * Embed the CLI template/migration assets into a generated TypeScript module.
 * The binary extracts them to a cache directory before importing the CLI.
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cli = resolve(root, "../cli");
const out = resolve(root, "src/assets.generated.ts");
const assets = {};

function walk(dir, prefix) {
  if (!statSync(dir, { throwIfNoEntry: false })?.isDirectory()) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, `${prefix}${entry.name}/`);
    else {
      const rel = `${prefix}${entry.name}`;
      assets[rel] = readFileSync(full).toString("base64");
    }
  }
}

walk(join(cli, "dist/templates"), "templates/");
walk(join(cli, "dist/migrations/manifests"), "migrations/manifests/");
assets["package.json"] = readFileSync(join(cli, "package.json")).toString("base64");

const hash = createHash("sha256");
for (const key of Object.keys(assets).sort()) {
  hash.update(key);
  hash.update(assets[key]);
}
const buildId = hash.digest("hex").slice(0, 16);

writeFileSync(
  out,
  `// Generated by packages/runtime/scripts/build-assets.mjs. Do not edit.
export const ASSET_BUILD_ID = ${JSON.stringify(buildId)};
export const ASSETS: Record<string, string> = ${JSON.stringify(assets, null, 2)};
`,
  "utf8",
);
console.log(`wrote ${out} (${Object.keys(assets).length} assets, ${buildId})`);
