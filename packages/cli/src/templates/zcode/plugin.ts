/**
 * Project-local ZCode plugin templates.
 *
 * ZCode loads `.zcode/plugins/phronia` through `plugins.dirs` as an `inline`
 * plugin and enables it by default. The hook commands use `type: "process"`
 * and `${ZCODE_PLUGIN_ROOT}`, so they never depend on the tool cwd.
 */

import { VERSION } from "../../constants/version.js";

export const ZCODE_PLUGIN_DIR = ".zcode/plugins/phronia";
export const ZCODE_PLUGIN_ID = "phronia@inline";

export function zcodePluginFiles(): Map<string, string> {
  return new Map([
    [
      `${ZCODE_PLUGIN_DIR}/.zcode-plugin/plugin.json`,
      `${JSON.stringify(
        {
          name: "phronia",
          version: VERSION,
          description:
            "Phronia project-local ZCode plugin: resolves the .phronia root and delegates context rendering to the Phronia CLI.",
          author: { name: "Phronia" },
          license: "AGPL-3.0",
        },
        null,
        2,
      )}\n`,
    ],
    [
      `${ZCODE_PLUGIN_DIR}/hooks/hooks.json`,
      `${JSON.stringify(
        {
          hooks: {
            SessionStart: [
              {
                matcher: "startup|clear|compact",
                hooks: [
                  {
                    type: "process",
                    command: "node",
                    args: [
                      "${ZCODE_PLUGIN_ROOT}/hooks/bridge.mjs",
                      "--event",
                      "session-start",
                    ],
                    timeoutMs: 30000,
                  },
                ],
              },
            ],
            UserPromptSubmit: [
              {
                hooks: [
                  {
                    type: "process",
                    command: "node",
                    args: [
                      "${ZCODE_PLUGIN_ROOT}/hooks/bridge.mjs",
                      "--event",
                      "user-prompt",
                    ],
                    timeoutMs: 15000,
                  },
                ],
              },
            ],
            PreToolUse: [
              {
                matcher: "Agent|Task",
                hooks: [
                  {
                    type: "process",
                    command: "node",
                    args: [
                      "${ZCODE_PLUGIN_ROOT}/hooks/bridge.mjs",
                      "--event",
                      "subagent-spawn",
                    ],
                    timeoutMs: 30000,
                  },
                ],
              },
              {
                matcher: "Bash",
                hooks: [
                  {
                    type: "process",
                    command: "node",
                    args: [
                      "${ZCODE_PLUGIN_ROOT}/hooks/bridge.mjs",
                      "--event",
                      "pre-shell",
                    ],
                    timeoutMs: 15000,
                  },
                ],
              },
            ],
          },
        },
        null,
        2,
      )}\n`,
    ],
    [`${ZCODE_PLUGIN_DIR}/hooks/bridge.mjs`, BRIDGE],
  ]);
}

const BRIDGE = `#!/usr/bin/env node
// Generated by Phronia. Delegates to \`phronia hook\`, which resolves the
// nearest .phronia root from ZCODE_PROJECT_DIR/cwd. The plugin path comes from
// ZCODE_PLUGIN_ROOT, so this file is stable when the tool cwd changes.

import { spawnSync } from "node:child_process";

const event = readArg("--event") ?? "session-start";
const cli = resolveCli();
const useShell =
  process.platform === "win32" && /\\.(cmd|bat)$/i.test(cli.command);
const result = spawnSync(
  cli.command,
  [...cli.args, "hook", "--platform", "zcode", "--event", event],
  {
    stdio: "inherit",
    env: process.env,
    // Windows ships the CLI as phronia.cmd; cmd.exe is required to execute a
    // batch shim. POSIX (and node/python paths) run the argv directly.
    shell: useShell,
  },
);

if (result.error) {
  process.stderr.write(
    \`phronia-zcode-plugin: \${result.error.message}\\n\`,
  );
  process.exit(1);
}
process.exit(result.status ?? 1);

function readArg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : null;
}

function resolveCli() {
  const explicit = process.env.PHRONIA_CLI_PATH?.trim();
  if (explicit) {
    if (explicit.endsWith(".js")) {
      return { command: "node", args: [explicit] };
    }
    if (explicit.endsWith(".py")) {
      return {
        command: process.platform === "win32" ? "python" : "python3",
        args: [explicit],
      };
    }
    return { command: explicit, args: [] };
  }
  return {
    command: process.platform === "win32" ? "phronia.cmd" : "phronia",
    args: [],
  };
}
`;
