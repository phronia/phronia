/**
 * Capability matrix renderers.
 *
 * `phronia platforms --matrix` (table), `--markdown` (docs page), and the
 * `--check` drift comparison all render from the same code so the checked-in
 * `docs/platform-matrix.md` cannot describe a different matrix.
 */

import { CAPABILITIES, PLATFORM_IDS, type Mechanism } from "@phronia/core";
import { AI_TOOLS } from "../types/ai-tools.js";

export function formatMechanism(mechanism: Mechanism): string {
  if (mechanism.kind === "none") return "—";
  if ("event" in mechanism && mechanism.event) return `${mechanism.kind} ${mechanism.event}`;
  return mechanism.detail ? `${mechanism.kind} ${mechanism.detail}` : mechanism.kind;
}

function detail(mechanism: Mechanism): string {
  if (mechanism.kind === "none") return mechanism.reason;
  return mechanism.detail ?? "";
}

function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function renderMatrixTable(): string {
  const header = [
    "Platform".padEnd(16),
    "SessionStart".padEnd(34),
    "Subagent".padEnd(34),
    "WorkflowState".padEnd(34),
    "Shell".padEnd(24),
    "Loop",
  ].join(" ");
  const lines = [header];
  for (const id of PLATFORM_IDS) {
    const capabilities = CAPABILITIES[id];
    lines.push(
      [
        id.padEnd(16),
        formatMechanism(capabilities.behavior.sessionStart).padEnd(34),
        formatMechanism(capabilities.behavior.subagentContext).padEnd(34),
        formatMechanism(capabilities.behavior.workflowState).padEnd(34),
        formatMechanism(capabilities.behavior.shellIdentity).padEnd(24),
        capabilities.loopControl,
      ].join(" "),
    );
  }
  return lines.join("\n");
}

export function renderMatrixMarkdown(): string {
  const lines: string[] = [
    "# Platform capability matrix",
    "",
    "Generated by `phronia platforms --matrix --markdown`. Do not edit by hand.",
    "",
    "| Platform | Session start | Sub-agent context | Workflow state | Shell identity | Agent definitions | Loop |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const id of PLATFORM_IDS) {
    const capabilities = CAPABILITIES[id];
    const behavior = capabilities.behavior;
    lines.push(
      `| \`${id}\` | ${[
        formatMechanism(behavior.sessionStart),
        formatMechanism(behavior.subagentContext),
        formatMechanism(behavior.workflowState),
        formatMechanism(behavior.shellIdentity),
        formatMechanism(behavior.agentDefinitions),
        capabilities.loopControl,
      ]
        .map(cell)
        .join(" | ")} |`,
    );
  }

  lines.push(
    "",
    "## Environment capabilities",
    "",
    "These are platform-level capabilities, not the current project's state. A project",
    "that happens to lack a git remote does not change the platform declaration.",
    "",
    "| Platform | git repo | git remote | symlinks |",
    "|---|---|---|---|",
  );
  for (const id of PLATFORM_IDS) {
    const environment = CAPABILITIES[id].environment;
    lines.push(
      `| \`${id}\` | ${environment.gitRepo} | ${environment.gitRemote} | ${environment.symlinks} |`,
    );
  }

  lines.push(
    "",
    "## Mechanism details and evidence",
    "",
    "| Platform | Session start detail | Sub-agent detail | Evidence |",
    "|---|---|---|---|",
  );
  for (const id of PLATFORM_IDS) {
    const capabilities = CAPABILITIES[id];
    const evidence = capabilities.evidence;
    lines.push(
      `| \`${id}\` | ${[
        detail(capabilities.behavior.sessionStart) || "—",
        detail(capabilities.behavior.subagentContext) || "—",
        `${evidence.verifiedAt}, ${evidence.verifiedBy}${evidence.notes ? `: ${evidence.notes}` : ""}`,
      ]
        .map(cell)
        .join(" | ")} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

export interface MatrixCheckResult {
  problems: string[];
}

/**
 * Structural checks that do not need the project's files. The caller adds
 * template-directory and docs drift checks where it knows the filesystem.
 */
export function checkMatrixStructure(): MatrixCheckResult {
  const problems: string[] = [];
  for (const id of PLATFORM_IDS) {
    if (!AI_TOOLS[id]) {
      problems.push(`${id}: missing AI_TOOLS entry`);
    }
    if (!CAPABILITIES[id]) {
      problems.push(`${id}: missing capability entry`);
    }
  }
  return { problems };
}
