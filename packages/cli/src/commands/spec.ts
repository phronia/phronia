/**
 * `phronia spec` — status, verification, and bootstrap planning.
 *
 * Bootstrap never invents architecture prose here; it reports what is
 * missing and can create a draft skeleton. Content generation stays with the
 * bundled skill so the command remains deterministic.
 */

import fs from "node:fs";
import path from "node:path";
import { readSpecStatuses, writeSpecStatus, type SpecStatus } from "@phronia/core";

export interface SpecOptions {
  cwd: string;
  json?: boolean;
  by?: string;
  dryRun?: boolean;
  write?: boolean;
}

export function runSpecStatus(options: SpecOptions): number {
  const summary = readSpecStatuses(options.cwd);
  if (options.json) {
    process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
    return 0;
  }
  for (const file of summary.files) {
    process.stdout.write(`${file.status.padEnd(11)} ${file.path}\n`);
  }
  process.stdout.write(
    `\n${summary.files.length} spec file(s): ${summary.counts.verified} verified, ${summary.counts.draft} draft, ${summary.counts.deprecated} deprecated.\n`,
  );
  return 0;
}

export function runSpecSetStatus(
  status: SpecStatus,
  paths: readonly string[],
  options: SpecOptions,
): number {
  if (paths.length === 0) {
    process.stderr.write(`usage: phronia spec ${status === "verified" ? "verify" : "deprecate"} <path...>\n`);
    return 2;
  }
  let failed = 0;
  for (const file of paths) {
    if (!writeSpecStatus(options.cwd, file, status, { by: options.by })) {
      process.stderr.write(`not found: ${file}\n`);
      failed += 1;
    } else if (!options.json) {
      process.stdout.write(`${file}: ${status}\n`);
    }
  }
  if (options.json) {
    process.stdout.write(
      `${JSON.stringify({ status, updated: paths.length - failed, missing: failed }, null, 2)}\n`,
    );
  }
  return failed > 0 ? 1 : 0;
}

export function runSpecBootstrap(options: SpecOptions): number {
  const specRoot = path.join(options.cwd, ".phronia", "spec");
  const missing: string[] = [];
  if (fs.existsSync(specRoot)) {
    for (const dir of fs.readdirSync(specRoot, { withFileTypes: true })) {
      if (!dir.isDirectory()) continue;
      const packageDir = path.join(specRoot, dir.name);
      for (const layer of fs.readdirSync(packageDir, { withFileTypes: true })) {
        if (!layer.isDirectory()) continue;
        const index = path.join(packageDir, layer.name, "index.md");
        if (!fs.existsSync(index)) {
          missing.push(
            path.relative(options.cwd, index).split(path.sep).join("/"),
          );
        }
      }
    }
  }

  const plan = { missing, dryRun: options.dryRun === true };
  if (options.json) {
    process.stdout.write(`${JSON.stringify(plan, null, 2)}\n`);
  } else if (missing.length === 0) {
    process.stdout.write("Spec index is complete.\n");
  } else {
    process.stdout.write("Missing spec index files:\n");
    for (const file of missing) process.stdout.write(`  ${file}\n`);
  }

  if (options.write && !options.dryRun) {
    for (const relative of missing) {
      const target = path.join(options.cwd, relative);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(
        target,
        [
          "---",
          "phronia:",
          "  status: draft",
          "  source: bootstrap",
          "---",
          "",
          `# ${path.basename(path.dirname(relative))}`,
          "",
          "> Draft generated by `phronia spec bootstrap`. Fill this in during",
          "> `/phronia:before-dev` or `phronia spec verify`.",
          "",
        ].join("\n"),
        "utf8",
      );
    }
    if (missing.length > 0) {
      process.stdout.write(`Created ${missing.length} draft index file(s).\n`);
    }
  }
  return 0;
}
