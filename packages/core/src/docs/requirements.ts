/**
 * `docs/requirements.md` - deterministic projection of the task ledger.
 *
 * No LLM and no prose: the file answers "what has been planned, built, and
 * archived" from `.phronia/tasks/<task>/task.json`. Regenerate on archive.
 */

import fs from "node:fs";
import path from "node:path";
import { LAYOUT } from "../layout/index.js";
import { openState } from "../state/index.js";

export interface RequirementRow {
  id: string;
  title: string;
  status: string;
  package: string | null;
  date: string;
  ref: string;
  archived: boolean;
}

export function projectRequirements(root: string): RequirementRow[] {
  const state = openState({ root });
  const rows: RequirementRow[] = [];
  for (const task of state.tasks.list({ includeArchived: true })) {
    const record = state.tasks.read(task.ref);
    if (!record) continue;
    const archived = task.archived;
    const month = task.archiveMonth ?? "";
    rows.push({
      id: record.id,
      title: record.title,
      status: record.status ?? "unknown",
      package: record.package,
      date: archived
        ? month
        : typeof record.raw.createdAt === "string"
          ? record.raw.createdAt
          : "",
      ref: task.ref,
      archived,
    });
  }
  return rows.sort(
    (a, b) => b.date.localeCompare(a.date) || a.id.localeCompare(b.id),
  );
}

export function renderRequirements(root: string): string {
  const rows = projectRequirements(root);
  const active = rows.filter((row) => !row.archived);
  const archived = rows.filter((row) => row.archived);
  const lines = [
    "# Requirements",
    "",
    "<!-- Generated by `phronia docs generate`. Do not edit by hand. -->",
    "",
    `Generated from ${rows.length} task record(s): ${active.length} active, ${archived.length} archived.`,
    "",
    "## Active",
    "",
    "| Task | Title | Status | Package | Created |",
    "|---|---|---|---|---|",
    ...active.map(requirementRow),
    "",
    "## Archived",
    "",
    "| Task | Title | Status | Package | Month |",
    "|---|---|---|---|---|",
    ...archived.map(requirementRow),
    "",
  ];
  return lines.join("\n");
}

export function writeRequirements(root: string, options: { check?: boolean } = {}): {
  path: string;
  changed: boolean;
  content: string;
} {
  const content = renderRequirements(root);
  const target = path.join(root, "docs", "requirements.md");
  const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  const changed = existing !== content;
  if (!options.check && changed) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, "utf8");
  }
  return { path: target, changed, content };
}

function requirementRow(row: RequirementRow): string {
  return `| \`${cell(row.id)}\` | ${cell(row.title)} | ${cell(row.status)} | ${cell(
    row.package ?? "-",
  )} | ${cell(row.date || "-")} |`;
}

function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

/** Guard used by task archive: refuse when a linked worktree still exists. */
export function archiveWorktreeGuard(root: string, taskRef: string): string | null {
  const state = openState({ root });
  const record = state.tasks.read(taskRef);
  if (!record) return null;
  const worktree = record.raw.worktree_path;
  if (typeof worktree === "string" && worktree && fs.existsSync(worktree)) {
    return `task has a worktree at ${worktree}; run \`phronia task worktree remove\` first`;
  }
  return null;
}

export function layoutWorktreesPath(root: string): string {
  return path.join(root, LAYOUT.paths.worktrees);
}
